'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const {
  findStaleBusyIssues,
  filterStaleWithoutLiveActivity,
  idleThresholdHours,
  buildWatchdogComment,
  listOpenBusyIssues,
  parseArgs,
  WATCHDOG_MARKER,
  MAX_PAGES,
} = require('./issue_busy_watchdog');
const { loadConfig } = require('./issue_pipeline_v2_config');
const { buildLaunchPending } = require('./issue_pipeline_v2_launch');
const { buildRunMarker } = require('../.github/scripts/agent-payload-lib');

const config = loadConfig();
const ENGINE = config.engine.logins;
const NOW = Date.parse('2026-11-24T12:00:00Z');
const hoursAgo = (h) => new Date(NOW - h * 3600 * 1000).toISOString();

test('findStaleBusyIssues selects busy issues idle past the threshold', () => {
  const issues = [
    { number: 2555, title: 'stalled', updated_at: hoursAgo(17), labels: [{ name: 'busy' }, { name: 'light-plan' }], body: '' },
    { number: 10, title: 'fresh busy', updated_at: hoursAgo(1), labels: ['busy'], body: '' },
    { number: 11, title: 'stale but not busy', updated_at: hoursAgo(40), labels: [{ name: 'light-plan' }] },
    { number: 12, title: 'busy PR', updated_at: hoursAgo(40), labels: ['busy'], pull_request: {} },
  ];
  const stale = findStaleBusyIssues(issues, { now: NOW, config, thresholdOverride: 6 });
  assert.deepEqual(
    stale.map((s) => s.number),
    [2555],
  );
  assert.equal(stale[0].idle_hours, 17);
  assert.equal(stale[0].threshold_hours, 6);
});

test('findStaleBusyIssues uses config stalledInactivityHours when no CLI override', () => {
  const issues = [{ number: 1, title: 't', updated_at: hoursAgo(20), labels: ['busy'], body: '' }];
  assert.equal(findStaleBusyIssues(issues, { now: NOW, config }).length, 0);
  const issues2 = [{ number: 2, title: 't', updated_at: hoursAgo(25), labels: ['busy'], body: '' }];
  assert.equal(findStaleBusyIssues(issues2, { now: NOW, config }).length, 1);
});

test('idleThresholdHours resolves Method PR and light-plan to the same config limit', () => {
  const prBody = '### Delivery plan\n\n**Method:** `PR` — one PR to `main`';
  const lpBody = '### Delivery plan\n\n**Method:** light-plan\n\n**Goal:** x';
  const want = config.limits.stalledInactivityHours;
  assert.equal(idleThresholdHours({ body: prBody }, config, undefined), want);
  assert.equal(idleThresholdHours({ body: lpBody }, config, undefined), want);
  assert.equal(idleThresholdHours({ body: lpBody }, config, 3), 3);
});

test('findStaleBusyIssues treats exactly-at-threshold as stale', () => {
  const issues = [{ number: 1, title: 't', updated_at: hoursAgo(6), labels: ['busy'], body: '' }];
  assert.equal(findStaleBusyIssues(issues, { now: NOW, config, thresholdOverride: 6 }).length, 1);
});

test('findStaleBusyIssues returns nothing when no busy issues are idle', () => {
  assert.deepEqual(findStaleBusyIssues([], { now: NOW, config }), []);
});

test('buildWatchdogComment carries the marker, idle hours and the footer', () => {
  const body = buildWatchdogComment({ number: 2555, idle_hours: 17 }, 6);
  assert.match(body, new RegExp(WATCHDOG_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
  assert.match(body, /about 17 h/);
  assert.match(body, /threshold 6 h/);
  assert.match(body, /run marker|launch record/);
  assert.match(body, /Generated by \[Claude Code\]/);
});

test('parseArgs defaults to a dry run with no threshold override', () => {
  assert.deepEqual(parseArgs([]), { apply: false, thresholdOverride: undefined });
  assert.deepEqual(parseArgs(['--apply', '--threshold-hours', '2']), { apply: true, thresholdOverride: 2 });
});

test('parseArgs rejects a non-positive threshold', () => {
  assert.throws(() => parseArgs(['--threshold-hours', '0']), /positive number/);
});

test('buildWatchdogComment names the light-plan resume only for light-plan issues', () => {
  const lp = buildWatchdogComment({ number: 9, idle_hours: 8, labels: ['busy', 'light-plan'] }, 24);
  assert.match(lp, /continue light-plan #9/);
  const other = buildWatchdogComment({ number: 10, idle_hours: 8, labels: ['busy', 'PR'] }, 24);
  assert.doesNotMatch(other, /light-plan/);
  assert.match(other, /\/babysit-plus/);
  assert.match(other, /heuristic/);
});

test('findStaleBusyIssues carries labels for the comment', () => {
  const [stale] = findStaleBusyIssues(
    [{ number: 3, title: 't', updated_at: hoursAgo(9), labels: [{ name: 'busy' }, { name: 'light-plan' }], body: '' }],
    { now: NOW, config, thresholdOverride: 6 },
  );
  assert.deepEqual(stale.labels, ['busy', 'light-plan']);
});

test('filterStaleWithoutLiveActivity skips when a fresh run marker is present', () => {
  const stale = [{ number: 1, title: 't', idle_hours: 30, threshold_hours: 24, labels: ['busy'] }];
  const ts = hoursAgo(1);
  const comments = {
    1: [
      {
        user: { login: 'pawpet-bot' },
        body: buildRunMarker({ agentId: 'bc', runId: 'r', status: 'running' }),
        created_at: ts,
        updated_at: ts,
      },
    ],
  };
  assert.deepEqual(filterStaleWithoutLiveActivity(stale, comments, { now: NOW, config }), []);
});

test('filterStaleWithoutLiveActivity flags stale marker past stalledInactivityHours', () => {
  const stale = [{ number: 1, title: 't', idle_hours: 30, threshold_hours: 24, labels: ['busy'] }];
  const ts = hoursAgo(config.limits.stalledInactivityHours + 1);
  const comments = {
    1: [
      {
        user: { login: 'pawpet-bot' },
        body: buildRunMarker({ agentId: 'bc', runId: 'r', status: 'running' }),
        created_at: ts,
        updated_at: ts,
      },
    ],
  };
  assert.deepEqual(filterStaleWithoutLiveActivity(stale, comments, { now: NOW, config }), stale);
});

test('filterStaleWithoutLiveActivity skips launch-pending', () => {
  const stale = [{ number: 2, title: 't', idle_hours: 30, threshold_hours: 24, labels: ['busy'] }];
  const body = buildLaunchPending({ agent: 'pawpet-bot' });
  const comments = { 2: [{ user: { login: ENGINE[0] }, body, created_at: hoursAgo(2), updated_at: hoursAgo(2) }] };
  assert.deepEqual(filterStaleWithoutLiveActivity(stale, comments, { now: NOW, config }), []);
});

function pagedFetch(pages) {
  const calls = [];
  const fetchImpl = async (url) => {
    calls.push(url);
    const page = Number(new URL(url).searchParams.get('page'));
    const batch = pages[page - 1] || [];
    return { ok: true, json: async () => batch };
  };
  return { fetchImpl, calls };
}

test('listOpenBusyIssues follows pages until a short page', async () => {
  const full = Array.from({ length: 100 }, (_, i) => ({ number: i + 1 }));
  const { fetchImpl, calls } = pagedFetch([full, [{ number: 101 }]]);
  const issues = await listOpenBusyIssues({ token: 't', repository: 'o/r', fetchImpl });
  assert.equal(issues.length, 101);
  assert.equal(calls.length, 2);
});

test('listOpenBusyIssues fails loudly instead of truncating at the page cap', async () => {
  const full = Array.from({ length: 100 }, (_, i) => ({ number: i + 1 }));
  const pages = Array.from({ length: MAX_PAGES }, () => full);
  const { fetchImpl } = pagedFetch(pages);
  await assert.rejects(listOpenBusyIssues({ token: 't', repository: 'o/r', fetchImpl }), /raise MAX_PAGES/);
});
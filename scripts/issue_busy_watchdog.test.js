'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const {
  findWallClockIdleBusyIssues,
  buildWatchdogComment,
  listOpenBusyIssues,
  parseArgs,
  selectStaleBusyIssues,
  WATCHDOG_MARKER,
  MAX_PAGES,
} = require('./issue_busy_watchdog');
const { loadConfig } = require('./issue_pipeline_v2_config');

const NOW = Date.parse('2026-11-24T12:00:00Z');
const hoursAgo = (h) => new Date(NOW - h * 3600 * 1000).toISOString();
const CONFIG = loadConfig();

test('findWallClockIdleBusyIssues selects busy issues idle past the threshold', () => {
  const issues = [
    { number: 2555, title: 'stalled', updated_at: hoursAgo(25), labels: [{ name: 'busy' }, { name: 'light-plan' }], body: '' },
    { number: 10, title: 'fresh busy', updated_at: hoursAgo(1), labels: ['busy'], body: '' },
    { number: 11, title: 'stale but not busy', updated_at: hoursAgo(40), labels: [{ name: 'light-plan' }], body: '' },
    { number: 12, title: 'busy PR', updated_at: hoursAgo(40), labels: ['busy'], pull_request: {}, body: '' },
  ];
  const stale = findWallClockIdleBusyIssues(issues, { now: NOW, thresholdHours: 24 });
  assert.deepEqual(
    stale.map((s) => s.number),
    [2555],
  );
  assert.equal(stale[0].idle_hours, 25);
  assert.equal(stale[0].thresholdHours, 24);
});

test('findWallClockIdleBusyIssues treats exactly-at-threshold as stale', () => {
  const issues = [{ number: 1, title: 't', updated_at: hoursAgo(24), labels: ['busy'], body: '' }];
  assert.equal(findWallClockIdleBusyIssues(issues, { now: NOW, thresholdHours: 24 }).length, 1);
});

test('buildWatchdogComment carries the marker, idle hours and the footer', () => {
  const body = buildWatchdogComment({ number: 2555, idle_hours: 25 }, 24);
  assert.match(body, new RegExp(WATCHDOG_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
  assert.match(body, /about 25 h/);
  assert.match(body, /threshold 24 h/);
  assert.match(body, /launch\/run markers/);
  assert.match(body, /Generated by \[Claude Code\]/);
});

test('parseArgs defaults to a dry run with unset threshold', () => {
  assert.deepEqual(parseArgs([]), { apply: false, thresholdHours: null });
  assert.deepEqual(parseArgs(['--apply', '--threshold-hours', '2']), { apply: true, thresholdHours: 2 });
});

test('parseArgs rejects a non-positive threshold', () => {
  assert.throws(() => parseArgs(['--threshold-hours', '0']), /positive number/);
});

test('buildWatchdogComment names the light-plan resume only for light-plan issues', () => {
  const lp = buildWatchdogComment({ number: 9, idle_hours: 8, labels: ['busy', 'light-plan'] }, 24);
  assert.match(lp, /continue light-plan #9/);
  const other = buildWatchdogComment({ number: 10, idle_hours: 8, labels: ['busy', 'PR'] }, 24);
  assert.doesNotMatch(other, /light-plan/);
  assert.match(other, /\/babysit-plus/);
});

test('selectStaleBusyIssues skips live marker after wall-clock idle', async () => {
  const issues = [
    {
      number: 99,
      title: 'quiet but live',
      updated_at: hoursAgo(30),
      labels: ['busy'],
      body: '### Delivery plan\n\nMethod: PR\n',
    },
  ];
  const fetchComments = async () => [
    {
      id: 1,
      body: '<!-- cursor-agent-run: {"status":"running"} -->',
      created_at: hoursAgo(1),
      updated_at: hoursAgo(1),
      user: { login: 'pawpet-bot' },
    },
  ];
  const stale = await selectStaleBusyIssues({
    issues,
    now: NOW,
    overrideHours: null,
    config: CONFIG,
    engineLogins: CONFIG.engine.logins,
    fetchComments,
  });
  assert.deepEqual(stale.map((s) => s.number), []);
});

function pagedFetch(pages) {
  const calls = [];
  const fetchImpl = async (url) => {
    calls.push(url);
    const page = Number(new URL(url).searchParams.get('page'));
    const batch = pages[page - 1] || [];
    return { ok: true, json: async () => batch };
  };
  return { fetchImpl, calls };
}

test('listOpenBusyIssues follows pages until a short page', async () => {
  const full = Array.from({ length: 100 }, (_, i) => ({ number: i + 1 }));
  const { fetchImpl, calls } = pagedFetch([full, [{ number: 101 }]]);
  const issues = await listOpenBusyIssues({ token: 't', repository: 'o/r', fetchImpl });
  assert.equal(issues.length, 101);
  assert.equal(calls.length, 2);
});

test('listOpenBusyIssues fails loudly instead of truncating at the page cap', async () => {
  const full = Array.from({ length: 100 }, (_, i) => ({ number: i + 1 }));
  const pages = Array.from({ length: MAX_PAGES }, () => full);
  const { fetchImpl } = pagedFetch(pages);
  await assert.rejects(listOpenBusyIssues({ token: 't', repository: 'o/r', fetchImpl }), /raise MAX_PAGES/);
});
#!/usr/bin/env node
'use strict';

/**
 * Watchdog for issues left `busy` after their agent run has stopped.
 *
 * An issue gets `busy` when an agent starts work. If that run ends without
 * clearing the label (for example, after a merge with no closing comment), the
 * issue sits busy and nothing picks it up. This script lists open `busy`
 * issues whose last activity is older than the per-issue idle threshold, after
 * skipping issues whose pipeline run or launch markers show fresh live work.
 *
 * Dry run by default. `--apply` posts one comment per stale issue. The comment
 * moves the issue's updated_at, so each issue is reported at most once per
 * threshold window.
 *
 * Usage (needs GITHUB_TOKEN and GITHUB_REPOSITORY=owner/repo):
 *   node scripts/issue_busy_watchdog.js [--threshold-hours N] [--apply]
 *
 * When `--threshold-hours` is omitted, idle time uses `limits.stalledInactivityHours`
 * from `.github/pipeline-agents.json` (currently 24 h), not the historical 6 h default.
 *
 * @module scripts/issue_busy_watchdog
 */

// CLI only — before any GitHub fetch: sandbox egress needs NODE_USE_ENV_PROXY at process start.
if (require.main === module) {
  require('./lib/env_proxy_reexec').reexecWithEnvProxy();
}

const {
  hasLivePipelineActivity,
  idleThresholdHoursForIssue,
  loadWatchdogLimits,
} = require('./lib/pipeline_busy_activity');
const { loadConfig } = require('./issue_pipeline_v2_config');

const MAX_PAGES = 50;
const MAX_COMMENT_PAGES = 20;
/** Cap comment fetches per run to limit GitHub REST rate use on large boards. */
const MAX_MARKER_CHECKS_PER_RUN = 25;
const COMMENT_FETCH_DELAY_MS = 100;
const BUSY_LABEL = 'busy';
const WATCHDOG_MARKER = '<!-- busy-watchdog -->';
const FOOTER = '_Generated by [Claude Code](https://claude.ai/code)_';

function labelName(label) {
  return typeof label === 'string' ? label : label && label.name;
}

function issueIsBusy(issue) {
  return (issue.labels || []).some((l) => labelName(l) === BUSY_LABEL);
}

/**
 * Issues past wall-clock idle threshold (before comment / marker checks).
 * @param {Array<object>} issues REST issue objects
 * @param {{ now?: number, thresholdHours: number }} opts
 */
function findWallClockIdleBusyIssues(issues, { now = Date.now(), thresholdHours }) {
  const cutoff = now - thresholdHours * 3600 * 1000;
  return issues
    .filter((issue) => !issue.pull_request)
    .filter((issue) => issueIsBusy(issue))
    .filter((issue) => Date.parse(issue.updated_at) <= cutoff)
    .map((issue) => ({
      number: issue.number,
      title: issue.title,
      body: issue.body || '',
      updated_at: issue.updated_at,
      labels: (issue.labels || []).map(labelName),
      idle_hours: Math.floor((now - Date.parse(issue.updated_at)) / 3600000),
      thresholdHours,
    }));
}

function buildWatchdogComment(stale, thresholdHours) {
  const idle = stale.idle_hours;
  const isLightPlan = (stale.labels || []).includes('light-plan');
  const next = isLightPlan
    ? `Next step: resume the light-plan run (\`continue light-plan #${stale.number}\`).`
    : 'Next step: resume the owning PR with `/babysit-plus`, or clear `busy` and record the state here.';
  return [
    WATCHDOG_MARKER,
    `Watchdog: this issue has been \`busy\` with no activity for about ${idle} h (threshold ${thresholdHours} h).`,
    'Idle time is a heuristic: a long run that posts no comments looks the same unless launch/run markers say otherwise. Check the run before acting.',
    next,
    '',
    '---',
    FOOTER,
  ].join('\n');
}

async function listOpenBusyIssues({ token, repository, fetchImpl = fetch }) {
  const out = [];
  for (let page = 1; page <= MAX_PAGES; page += 1) {
    const url = `https://api.github.com/repos/${repository}/issues?state=open&labels=${BUSY_LABEL}&per_page=100&page=${page}`;
    const res = await fetchImpl(url, {
      headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
    });
    if (!res.ok) throw new Error(`list issues failed: HTTP ${res.status}`);
    const batch = await res.json();
    out.push(...batch);
    if (batch.length < 100) return out;
  }
  throw new Error(`list issues: more than ${MAX_PAGES * 100} open busy issues; raise MAX_PAGES instead of truncating`);
}

async function listIssueComments({ token, repository, issueNumber, fetchImpl = fetch }) {
  const out = [];
  for (let page = 1; page <= MAX_COMMENT_PAGES; page += 1) {
    const url = `https://api.github.com/repos/${repository}/issues/${issueNumber}/comments?per_page=100&page=${page}`;
    const res = await fetchImpl(url, {
      headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
    });
    if (!res.ok) throw new Error(`list comments for #${issueNumber} failed: HTTP ${res.status}`);
    const batch = await res.json();
    out.push(...batch);
    if (batch.length < 100) return out;
  }
  throw new Error(`list comments: more than ${MAX_COMMENT_PAGES * 100} comments on #${issueNumber}`);
}

/**
 * @param {object} opts
 * @param {Array<object>} opts.issues full busy issues from GitHub
 * @param {number} [opts.now]
 * @param {number|null} opts.overrideHours
 * @param {object} opts.config validated pipeline config
 * @param {string[]} opts.engineLogins
 * @param {Function} [opts.fetchComments] async (issueNumber) => comments
 */
async function selectStaleBusyIssues({
  issues,
  now = Date.now(),
  overrideHours = null,
  config,
  engineLogins,
  fetchComments,
  maxMarkerChecks = MAX_MARKER_CHECKS_PER_RUN,
  commentFetchDelayMs = COMMENT_FETCH_DELAY_MS,
}) {
  const staleCandidates = [];
  for (const issue of issues) {
    if (issue.pull_request || !issueIsBusy(issue)) continue;
    const thresholdHours = idleThresholdHoursForIssue({
      body: issue.body,
      config,
      overrideHours,
    });
    const idle = findWallClockIdleBusyIssues([issue], { now, thresholdHours });
    if (idle.length > 0) {
      staleCandidates.push(...idle);
    }
  }

  staleCandidates.sort((a, b) => b.idle_hours - a.idle_hours);
  const markerCheckSkipped = Math.max(0, staleCandidates.length - maxMarkerChecks);
  const toInspect = staleCandidates.slice(0, maxMarkerChecks);

  const stale = [];
  for (let i = 0; i < toInspect.length; i += 1) {
    const candidate = toInspect[i];
    if (i > 0 && commentFetchDelayMs > 0) {
      await new Promise((resolve) => setTimeout(resolve, commentFetchDelayMs));
    }
    const comments = await fetchComments(candidate.number);
    const limits = config.limits;
    if (
      hasLivePipelineActivity({
        comments,
        now,
        limits,
        engineLogins,
        issueIsBusy: true,
      })
    ) {
      continue;
    }
    stale.push(candidate);
  }
  return { stale, markerCheckSkipped };
}

function parseArgs(argv) {
  const args = { apply: false, thresholdHours: null };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--apply') args.apply = true;
    else if (argv[i] === '--threshold-hours') args.thresholdHours = Number(argv[++i]);
  }
  if (args.thresholdHours != null && (!Number.isFinite(args.thresholdHours) || args.thresholdHours <= 0)) {
    throw new Error('--threshold-hours must be a positive number');
  }
  return args;
}

async function main(argv = process.argv.slice(2), env = process.env) {
  const { apply, thresholdHours: overrideHours } = parseArgs(argv);
  const token = env.GITHUB_TOKEN;
  const repository = env.GITHUB_REPOSITORY;
  if (!token || !repository) throw new Error('GITHUB_TOKEN and GITHUB_REPOSITORY (owner/repo) are required');

  const config = loadConfig();
  const { engineLogins } = loadWatchdogLimits();

  const issues = await listOpenBusyIssues({ token, repository });
  const { stale, markerCheckSkipped } = await selectStaleBusyIssues({
    issues,
    overrideHours,
    config,
    engineLogins,
    fetchComments: (issueNumber) => listIssueComments({ token, repository, issueNumber }),
    maxMarkerChecks: MAX_MARKER_CHECKS_PER_RUN,
    commentFetchDelayMs: COMMENT_FETCH_DELAY_MS,
  });

  const defaultHours = config.limits.stalledInactivityHours;
  console.log(
    `busy-watchdog: ${stale.length} stale busy issue(s) of ${issues.length} open (config default ${defaultHours} h${
      overrideHours != null ? `, override ${overrideHours} h` : ''
    }${markerCheckSkipped > 0 ? `, ${markerCheckSkipped} wall-clock candidate(s) not marker-checked (cap ${MAX_MARKER_CHECKS_PER_RUN})` : ''})`,
  );
  for (const s of stale) {
    console.log(`  #${s.number} idle ${s.idle_hours} h (threshold ${s.thresholdHours} h): ${s.title}`);
    if (!apply) continue;
    const res = await fetch(`https://api.github.com/repos/${repository}/issues/${s.number}/comments`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github+json',
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ body: buildWatchdogComment(s, s.thresholdHours) }),
    });
    if (!res.ok) throw new Error(`comment on #${s.number} failed: HTTP ${res.status}`);
  }
  if (!apply && stale.length > 0) console.log('dry run: pass --apply to comment on these issues');
  return stale;
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}

module.exports = {
  findWallClockIdleBusyIssues,
  buildWatchdogComment,
  listOpenBusyIssues,
  listIssueComments,
  selectStaleBusyIssues,
  parseArgs,
  WATCHDOG_MARKER,
  MAX_PAGES,
  MAX_MARKER_CHECKS_PER_RUN,
};